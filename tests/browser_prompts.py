"""Local browser rehearsal for live prompt editing beside model selection."""
import json,os,time
from playwright.sync_api import sync_playwright,expect
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/google-chrome',headless=True)
    context=browser.new_context(base_url=os.getenv('TEST_BASE_URL','http://localhost:5181'),viewport={'width':1440,'height':1000})
    page=context.new_page();errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto('/');assert page.request.get('/api/bootstrap').json()['demo']
    page.get_by_role('button',name='Открыть локальное демо').click()
    page.locator('button.new-chat').click()
    page.get_by_role('button',name='Конфигурация',exact=True).click()
    page.get_by_role('combobox',name='Модель разговора').select_option('alice-flash')
    page.get_by_role('button',name='Создать промпт',exact=True).click()
    name='Исторический совет '+str(int(time.time()))
    page.get_by_role('textbox',name='Название промпта',exact=True).fill(name)
    page.get_by_role('textbox',name='Текст промпта',exact=True).fill('Представляй взгляды боярина при Петре Первом. Опирайся на предоставленные источники.')
    page.get_by_role('button',name='Создать',exact=True).click()
    expect(page.get_by_role('status')).to_have_text('Промпт создан')
    page.get_by_role('button',name='Подставить в настройки разговора').click()
    expect(page.get_by_role('combobox',name='Модель разговора')).to_have_value('alice-flash')
    selected=page.get_by_role('combobox',name='Инструкция разговора')
    expect(selected.locator('option:checked')).to_have_text(name)
    page.get_by_role('button',name='Сохранить настройки разговора').click()
    expect(page.get_by_role('status')).to_have_text('Сохранено')
    page.get_by_role('button',name='Редактировать промпт',exact=True).click()
    expect(page.get_by_role('button',name='Удалить промпт',exact=True)).to_be_disabled()
    updated='Представляй взгляды дворянина и боярина. Разделяй подтверждённые факты и реконструкцию.'
    page.get_by_role('textbox',name='Текст промпта',exact=True).fill(updated)
    page.get_by_role('button',name='Сохранить промпт',exact=True).click()
    expect(page.get_by_role('status')).to_have_text('Промпт сохранён. Следующие ответы используют новую версию.')
    page.set_viewport_size({'width':390,'height':844})
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
    page.screenshot(path='/tmp/gosboard-prompts-mobile.png',full_page=True)
    page.get_by_role('button',name='Разговор',exact=True).click()
    page.get_by_role('combobox',name='Инструкция разговора').select_option('default')
    page.get_by_role('button',name='Сохранить настройки разговора').click();expect(page.get_by_role('status')).to_have_text('Сохранено')
    page.get_by_role('button',name='Промпты',exact=True).click()
    page.get_by_role('combobox',name='Управляемый промпт').select_option(label=name)
    expect(page.get_by_role('textbox',name='Текст промпта',exact=True)).to_have_value(updated)
    page.once('dialog',lambda dialog:dialog.accept())
    page.get_by_role('button',name='Удалить промпт',exact=True).click()
    expect(page.get_by_role('status')).to_have_text('Промпт удалён')
    assert not any(p['label']==name for p in page.request.get('/api/editor/prompts').json()['prompts'])
    assert errors==[],errors
    print(json.dumps({'prompt_create_edit_select_delete':'passed','model_selection_preserved':'passed','in_use_deletion_guard':'passed','mobile':'passed','browser_errors':errors}))
    browser.close()
